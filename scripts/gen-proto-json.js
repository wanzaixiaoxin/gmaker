// ============================================================
// gen-proto-json.js — 从 spec/proto/*.proto 生成前端 protobuf descriptor
//
// 消除 web/index.html 中手写 PROTO_DESCRIPTOR 与 .proto 的漂移风险：
// 改为单一真相源（spec/proto/*.proto）→ 自动生成 web/js/proto_descriptor.js。
//
// 运行：node scripts/gen-proto-json.js
// 产物：web/js/proto_descriptor.js（赋值 window.PROTO_DESCRIPTOR）
//
// 依赖：protobufjs（开发依赖，见 node_modules）
// ============================================================

const fs = require('fs');
const path = require('path');
const protobuf = require('protobufjs');
const Long = require('long');

// protobufjs 处理 uint64/int64 需要 Long
protobuf.util.Long = Long;
protobuf.configure();

const ROOT = path.resolve(__dirname, '..');
const PROTO_DIR = path.join(ROOT, 'spec', 'proto');
const OUT_FILE = path.join(ROOT, 'web', 'js', 'proto_descriptor.js');

async function main() {
    const protoFiles = fs.readdirSync(PROTO_DIR)
        .filter(f => f.endsWith('.proto'))
        .sort();

    if (protoFiles.length === 0) {
        console.error('No .proto files found in ' + PROTO_DIR);
        process.exit(1);
    }

    // 加载所有 proto 到一个 Root（处理 import 依赖）
    const root = new protobuf.Root();
    root.resolvePath = function (origin, target) {
        // 所有 import 都相对于 spec/proto
        const p = path.join(PROTO_DIR, target);
        return fs.existsSync(p) ? p : null;
    };
    for (const f of protoFiles) {
        // 传相对 spec/proto 的文件名，让 resolvePath 统一解析
        await root.load(f, { keepCase: false });
    }

    const json = root.toJSON();

    // 输出为 JS 文件（赋值 window.PROTO_DESCRIPTOR），避免运行时 fetch/CORS
    const content =
        '// AUTO-GENERATED by scripts/gen-proto-json.js — DO NOT EDIT.\n' +
        '// 源：spec/proto/*.proto。重新生成：node scripts/gen-proto-json.js 或 make proto。\n' +
        'window.PROTO_DESCRIPTOR = ' + JSON.stringify(json, null, 0) + ';\n';

    fs.writeFileSync(OUT_FILE, content, 'utf8');

    const sizeKB = Math.round(fs.statSync(OUT_FILE).size / 1024);
    const packages = Object.keys(json.nested || {}).join(', ');
    console.log('Generated ' + path.relative(ROOT, OUT_FILE) + ' (' + sizeKB + ' KB)');
    console.log('Packages: ' + packages);
    console.log('Sources: ' + protoFiles.join(', '));
}

main().catch(e => {
    console.error('gen-proto-json failed:', e);
    process.exit(1);
});
